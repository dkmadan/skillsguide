export function getAllLabs(): LabDefinition[] {
  return allLabsCatalog;
}

export function getLabBySlug(slug: string): LabDefinition | undefined {
  return allLabsCatalog.find(lab => lab.slug === slug);
}

export function getLabsByDomain(domain: LabDomain): LabDefinition[] {
  return allLabsCatalog.filter(lab => lab.domain === domain);
}

export function getLabForSkill(skillSlug: string): LabDefinition | undefined {
  return allLabsCatalog.find(lab => lab.associatedSkillSlugs.includes(skillSlug));
}
